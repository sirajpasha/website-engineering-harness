#!/usr/bin/env node
/**
 * Generate and verify Claude Code subagent files.
 *
 *   agents/<name>.md                canonical prose definition (edit this)
 *   agents/<name>.contract.json     machine contract (write roots, may_spawn)
 *   agents/claude-subagents.json    description + tools per agent
 *      ──► .claude/agents/<name>.md  frontmatter + canonical body (GENERATED)
 *
 * The frontmatter `name` equals the contract file name, which is what Claude
 * Code reports as `agent_type` in hook payloads — so claude-hook.js can apply
 * the right contract to every subagent tool call.
 *
 * Usage: node scripts/agent-validation/sync-claude-agents.js [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '../../');
const agentsDir = path.join(rootDir, 'agents');
const claudeAgentsDir = path.join(rootDir, '.claude', 'agents');

export const VALID_TOOLS = ['Read', 'Grep', 'Glob', 'Write', 'Edit', 'MultiEdit', 'Bash', 'Agent', 'WebFetch', 'WebSearch', 'NotebookEdit'];
const GENERATED_NOTE = (name) =>
  `<!-- GENERATED by scripts/agent-validation/sync-claude-agents.js from agents/${name}.md, agents/${name}.contract.json and agents/claude-subagents.json. Edit those, then run \`npm run agents:sync\`. -->`;

const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));

export function listAgentNames() {
  return fs.readdirSync(agentsDir)
    .filter(f => f.endsWith('.contract.json'))
    .map(f => f.replace(/\.contract\.json$/, ''))
    .sort();
}

const yamlString = (s) => JSON.stringify(s); // JSON strings are valid YAML double-quoted scalars

/** Build the full text of .claude/agents/<name>.md */
export function buildSubagent(name) {
  const meta = readJson(path.join(agentsDir, 'claude-subagents.json'))[name];
  if (!meta) throw new Error(`No entry for '${name}' in agents/claude-subagents.json`);
  const contract = readJson(path.join(agentsDir, `${name}.contract.json`));
  const body = fs.readFileSync(path.join(agentsDir, `${name}.md`), 'utf8').replace(/\r\n/g, '\n');

  const lines = ['---', `name: ${name}`, `description: ${yamlString(meta.description)}`];
  if (meta.tools) {
    const tools = [...meta.tools];
    if (contract.may_spawn.length > 0 && !tools.includes('Agent')) tools.push('Agent');
    lines.push(`tools: ${tools.join(', ')}`);
  }
  lines.push('---', '', GENERATED_NOTE(name), '', body);
  return lines.join('\n');
}

/** Minimal frontmatter parser for the flat key: value form we generate. */
export function parseFrontmatter(text) {
  const m = text.replace(/\r\n/g, '\n').match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { data: {}, body: text, hasFrontmatter: false };
  const data = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith('"')) { try { v = JSON.parse(v); } catch { /* keep raw */ } }
    data[kv[1]] = v;
  }
  return { data, body: m[2], hasFrontmatter: true };
}

export function validateSubagents({ claudeAgentsDir: dir = claudeAgentsDir, log = () => {} } = {}) {
  const errors = [];
  for (const name of listAgentNames()) {
    const file = path.join(dir, `${name}.md`);
    if (!fs.existsSync(file)) { errors.push(`.claude/agents/${name}.md is missing (run npm run agents:sync)`); continue; }
    const actual = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    const { data, hasFrontmatter } = parseFrontmatter(actual);
    if (!hasFrontmatter) errors.push(`${name}: no YAML frontmatter — Claude Code cannot register it as a subagent`);
    else if (data.name !== name) errors.push(`${name}: frontmatter name '${data.name}' does not match filename`);
    let expected;
    try { expected = buildSubagent(name); } catch (e) { errors.push(`${name}: ${e.message}`); continue; }
    if (actual !== expected) errors.push(`${name}: .claude/agents/${name}.md is out of sync (drift) with agents/ sources — run npm run agents:sync`);
  }
  const passed = errors.length === 0;
  errors.forEach(e => log(`[✖] ${e}`));
  if (passed) log(`[✔] ${listAgentNames().length} Claude Code subagents are valid and in sync.`);
  return { passed, errors };
}

export function syncClaudeAgents() {
  fs.mkdirSync(claudeAgentsDir, { recursive: true });
  let written = 0;
  for (const name of listAgentNames()) {
    const out = path.join(claudeAgentsDir, `${name}.md`);
    const text = buildSubagent(name);
    if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== text) {
      fs.writeFileSync(out, text, 'utf8');
      written++;
    }
  }
  return written;
}

if (process.argv[1] && process.argv[1].endsWith('sync-claude-agents.js')) {
  if (process.argv.includes('--check')) {
    const r = validateSubagents({ log: console.log });
    process.exit(r.passed ? 0 : 1);
  }
  const n = syncClaudeAgents();
  console.log(`Synced Claude Code subagents: ${n} file(s) updated.`);
}

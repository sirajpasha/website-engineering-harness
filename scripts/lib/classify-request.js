/**
 * Classify a /website-create | /website-redesign | /website-improve request.
 * The command fixes the lifecycle (NEW_WEBSITE | REDESIGN | ENHANCE); keywords
 * infer a project sub-type. Weak signal => low confidence + a recorded assumption
 * (never a silent guess). Deterministic; no network or model calls.
 */
export const MODES = new Set([
  'NEW_WEBSITE', 'REDESIGN', 'ENHANCE', 'LANDING_PAGE', 'CORPORATE_WEBSITE', 'E_COMMERCE',
  'FULL_STACK_MVP', 'BOOKING_WEBSITE', 'CUSTOMER_PORTAL', 'CONTENT_WEBSITE',
]);

const BASE = { create: 'NEW_WEBSITE', redesign: 'REDESIGN', improve: 'ENHANCE' };

// Order matters: more specific types first.
const RULES = [
  ['E_COMMERCE', /\b(e-?commerce|online (shop|store)|shop(ping)?|cart|checkout|storefront|catalog(ue)? with prices)\b/i],
  ['BOOKING_WEBSITE', /\b(book(ing|ings)?|appointments?|reservations?|schedul(e|ing))\b/i],
  ['CUSTOMER_PORTAL', /\b(portal|log ?in|sign ?in|customer account|client area|dashboard for (customers|clients))\b/i],
  ['LANDING_PAGE', /\b(landing page|one-?page|single page|launch page|waitlist)\b/i],
  ['FULL_STACK_MVP', /\b(mvp|database|backend|full-?stack|api|user accounts?)\b/i],
  ['CONTENT_WEBSITE', /\b(blog|articles?|magazine|news|publication|documentation site|docs site)\b/i],
  ['CORPORATE_WEBSITE', /\b(company|corporate|business|firm|agency|export|import|services|enquir(y|ies)|about us)\b/i],
];

export function classifyRequest({ command, text = '', hasProject } = {}) {
  const base = BASE[command];
  if (!base) throw new Error(`Unknown command '${command}' (expected create|redesign|improve)`);
  const out = { command, base, subtype: null, confidence: 'high' };

  if (command !== 'create' && hasProject === false) {
    return { ...out, blocked: true, reason: `/website-${command} needs an existing project in the current directory; use /website-create for a new site.` };
  }
  if (command === 'create' && hasProject === true) {
    out.warning = 'A project already exists here. /website-create will not overwrite it; use /website-redesign or /website-improve, or choose an empty directory.';
  }

  const hit = RULES.find(([, re]) => re.test(text));
  if (hit) {
    out.subtype = hit[0];
  } else {
    out.subtype = 'CORPORATE_WEBSITE';
    out.confidence = 'low';
    out.assumption = {
      description: 'Project sub-type assumed to be CORPORATE_WEBSITE',
      reason: 'The request gave no signal for a more specific type (shop, booking, portal, landing page, MVP, content)',
      impact: 'Sitemap, page templates and backend scope; low if wrong because no backend is generated by default',
      confidence: 'low',
      validation: 'unvalidated',
    };
  }
  return out;
}
